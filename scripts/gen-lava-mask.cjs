/**
 * gen-lava-mask.cjs - builds src/shared/lavaMask.ts from assets/models/terrain.glb.
 * A cell (CELL m) is "open lava" when the highest terrain vertex in it AND in
 * its 8 neighbours is below the lava base surface (so bubbles up to ~6 m
 * radius never poke onto land), it lies inside the lava circle minus EDGE_M,
 * and it is outside the castle footprint + CASTLE_MARGIN_M.
 * Run: node scripts/gen-lava-mask.cjs  (re-run if terrain.glb or the castle moves)
 */
const fs = require('fs')
const CELL = 8, N = 100                     // 800 m scene
const TERRAIN_Y = 37                        // terrainSetup.ts position.y
const LAVA_Y = 49.58                        // WATER_BASE_Y
const CX = 400, CZ = 400, R = 368, EDGE_M = 16 // lava plane 736 m
const CASTLE = { x0: 294, x1: 433, z0: 239, z1: 456 }, CASTLE_MARGIN_M = 8
const b = fs.readFileSync('assets/models/terrain.glb'); const jl = b.readUInt32LE(12)
const j = JSON.parse(b.slice(20, 20 + jl).toString()); const bin = 20 + jl + 8
const top = new Float32Array(N * N).fill(-1e9)
for (const n of j.nodes) {
  if (n.mesh === undefined) continue
  const t = n.translation || [0, 0, 0], s = n.scale || [1, 1, 1]
  for (const p of j.meshes[n.mesh].primitives) {
    const a = j.accessors[p.attributes.POSITION], bv = j.bufferViews[a.bufferView], st = bv.byteStride || 12
    const o = bin + (bv.byteOffset || 0) + (a.byteOffset || 0)
    for (let i = 0; i < a.count; i++) {
      const x = b.readFloatLE(o + i * st) * s[0] + t[0], y = b.readFloatLE(o + i * st + 4) * s[1] + t[1] + TERRAIN_Y
      const z = b.readFloatLE(o + i * st + 8) * s[2] + t[2]
      const gx = Math.floor(x / CELL), gz = Math.floor(z / CELL)
      if (gx >= 0 && gz >= 0 && gx < N && gz < N && y > top[gz * N + gx]) top[gz * N + gx] = y
    }
  }
}
const bits = new Uint8Array(Math.ceil(N * N / 8)); let count = 0
for (let gz = 0; gz < N; gz++) for (let gx = 0; gx < N; gx++) {
  const wx = (gx + 0.5) * CELL, wz = (gz + 0.5) * CELL
  if ((wx - CX) ** 2 + (wz - CZ) ** 2 > (R - EDGE_M) ** 2) continue
  if (wx > CASTLE.x0 - CASTLE_MARGIN_M && wx < CASTLE.x1 + CASTLE_MARGIN_M && wz > CASTLE.z0 - CASTLE_MARGIN_M && wz < CASTLE.z1 + CASTLE_MARGIN_M) continue
  let ok = true
  for (let dz = -1; dz <= 1 && ok; dz++) for (let dx = -1; dx <= 1; dx++) {
    const x = gx + dx, z = gz + dz
    if (x < 0 || z < 0 || x >= N || z >= N) continue
    if (top[z * N + x] >= LAVA_Y) { ok = false; break }
  }
  if (!ok) continue
  const k = gz * N + gx; bits[k >> 3] |= 1 << (k & 7); count++
}
const out = `// AUTO-GENERATED by scripts/gen-lava-mask.cjs - do not edit by hand.
// ${N}x${N} cells of ${CELL} m; bit set = open lava (terrain below ${LAVA_Y} incl. neighbours,
// inside the lava circle minus ${EDGE_M} m, outside the castle footprint + ${CASTLE_MARGIN_M} m). ${count} cells.
export const LAVA_MASK_CELL_M = ${CELL}
export const LAVA_MASK_N = ${N}
export const LAVA_MASK_BASE64 = '${Buffer.from(bits).toString('base64')}'
`
fs.writeFileSync('src/shared/lavaMask.ts', out)
console.log('open lava cells', count, 'of', N * N, '=', Math.round(count * CELL * CELL / 1000), 'k m2')